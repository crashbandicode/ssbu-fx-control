#!/usr/bin/env python3
"""Regenerate reference/effect_names.txt: every effect-like string literal in
src/*.rs (move layers, Off tables, catalog, probe names) plus the
sys_* names the move scripts share. resolve_trace.py uses it to turn trace
hashes back into names. Add names by hand below the generated block if a
trace shows an unresolved hash and the dumped scripts name it. Previously
indexed names are retained so historical/untargeted traces remain decodable.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "reference" / "effect_names.txt"
LITERAL = re.compile(r'"([A-Za-z][A-Za-z0-9_]{2,63})"')
PREFIXES = ("sys_", "bg_", "P_", "null", "tex_")
SKIP = {"null"}


def looks_like_effect(name: str) -> bool:
    if name in SKIP:
        return False
    if name.startswith(PREFIXES):
        return True
    return "_" in name and name == name.lower() or name.startswith("P_")


def retained_names(text):
    lines = text.splitlines()
    # Match the delimiter as a whole line, not its mention in the header.
    # The last delimiter also recovers files emitted by the old substring split.
    marker = max((i for i, line in enumerate(lines) if line == "# manual"), default=len(lines))
    generated = {line for line in lines[:marker]
                 if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]+", line)}
    manual = [line for line in lines[marker + 1:] if line.strip()]
    return generated, manual


def main():
    names = set()
    for path in sorted((ROOT / "src").rglob("*.rs")):
        for literal in LITERAL.findall(path.read_text()):
            if looks_like_effect(literal):
                names.add(literal)
    manual = []
    if OUT.exists():
        previous, manual = retained_names(OUT.read_text())
        names.update(previous)
    lines = ["# generated by tools/export_effect_names.py; names below '# manual' are kept"]
    lines += sorted(names)
    lines.append("# manual")
    lines += manual
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} generated names, {len(manual)} manual, written to {OUT}")


if __name__ == "__main__":
    main()
