#!/usr/bin/env python3
"""Decode TRACE_EFFECTS fighter (110), stage-particle (114), and model (116) events.

Each code-110 row is the first request of one (effect name, actor category,
kind, status) combination. The plugin only knows Hash40 values; this tool
turns them back into names with a name list (one name per line; the default
is reference/effect_names.txt, regenerated by tools/export_effect_names.py)
and prints the layers per actor so a move's layer list can be written into
src/moves.rs from a real run instead of from the scripts alone.

Codes 117, 118 and 119 are the separate TRACE_STAGE_DIAGNOSTICS stream.
They are not folded into the 110/114/116 actor groups. 118 counts observed
model-hook calls, not frames. 119 is a first-seen predicate record, not
every particle call.

Usage:
  resolve_trace.py events.log [--names NAMES.txt ...] [--kind 0x6] [--json]
"""
import argparse
import json
import sys
import zlib
from collections import defaultdict
from pathlib import Path

TRACE_CODE = 110
STAGE_TRACE_CODE = 114
MODEL_TRACE_CODE = 116
STAGE_DIAG_CODE = 117
STAGE_MODEL_COUNT_CODE = 118
STAGE_PARTICLE_CODE = 119
CALLER_SENTINEL = 0xFFFFFFFF
PARTICLE_FLAGS = (
    (1, "name-hit"),
    (2, "caller-allowed"),
    (4, "stage-match"),
    (8, "row-off"),
)
MODEL_REASONS = {
    1: "found",
    2: "unregistered",
    3: "ambiguous",
    4: "contended",
    5: "disabled",
    6: "requested-native-hidden",
    7: "native-visible",
    8: "suppressed",
    9: "wrong-vtable",
    10: "wrong-stage",
}


def hash40(name: str) -> int:
    data = name.encode()
    return (len(data) << 32) | (zlib.crc32(data) & 0xFFFFFFFF)


def load_names(paths):
    table = {}
    for path in paths:
        for line in Path(path).read_text().splitlines():
            name = line.strip()
            if name and not name.startswith("#"):
                table[hash40(name)] = name
    return table


def unpack(b: int):
    category = b & 0xFF
    kind = (b >> 8) & 0xFFFF
    status = (b >> 24) & 0xFFFF
    ordinal = (b >> 40) & 0xFFFF
    if kind >= 0x8000:
        kind -= 0x10000
    if status >= 0x8000:
        status -= 0x10000
    return category, kind, status, ordinal


def read_events(path):
    rows = []
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if len(parts) < 5 or not parts[0].isdigit():
            continue
        code = int(parts[2])
        if code not in (TRACE_CODE, STAGE_TRACE_CODE, MODEL_TRACE_CODE):
            continue
        a, b = int(parts[3], 16), int(parts[4], 16)
        if code in (STAGE_TRACE_CODE, MODEL_TRACE_CODE):
            rows.append({"tick": int(parts[1]), "hash": a,
                         "category": 0xfe if code == STAGE_TRACE_CODE else 0xfd,
                         "kind": b >> 32, "status": -1, "ordinal": b & 0xffffffff})
            continue
        if a == 0:
            rows.append({"latched": bool(b & 1), "tick": int(parts[1])})
            continue
        category, kind, status, ordinal = unpack(b)
        rows.append({"tick": int(parts[1]), "hash": a, "category": category, "kind": kind,
                     "status": status, "ordinal": ordinal})
    return rows


def signed_bits(value, bits):
    value &= (1 << bits) - 1
    if value >= 1 << (bits - 1):
        value -= 1 << bits
    return value


def flag_names(flags):
    names = [name for bit, name in PARTICLE_FLAGS if flags & bit]
    extra = flags
    for bit, _name in PARTICLE_FLAGS:
        extra &= ~bit
    if extra:
        names.append(f"0x{extra:x}")
    return names


def read_stage_diagnostics(path):
    """Codes 117/118/119 only. 110/114/116 stay in read_events."""
    enabled = []
    counts = []
    particles = []
    for line in Path(path).read_text().splitlines():
        parts = line.split()
        if len(parts) < 5 or not parts[0].isdigit():
            continue
        code = int(parts[2])
        tick = int(parts[1])
        argument_a, argument_b = int(parts[3], 16), int(parts[4], 16)
        if code == STAGE_DIAG_CODE:
            enabled.append({"tick": tick, "enabled": bool(argument_a & 1)})
        elif code == STAGE_MODEL_COUNT_CODE:
            reason = argument_a & 0xFFFFFFFF
            counts.append({
                "tick": tick,
                "stage_id": signed_bits(argument_a >> 32, 32),
                "reason": reason,
                "reason_name": MODEL_REASONS.get(reason, f"reason {reason}"),
                "count": argument_b,
            })
        elif code == STAGE_PARTICLE_CODE:
            flags = (argument_b >> 32) & 0xFFFF
            caller = argument_b & 0xFFFFFFFF
            particles.append({
                "tick": tick,
                "hash": argument_a & 0xFFFFFFFFFF,
                "stage_id": signed_bits(argument_b >> 48, 16),
                "flags": flags,
                "flag_names": flag_names(flags),
                "caller": caller,
                "caller_unrepresentable": caller == CALLER_SENTINEL,
            })
    return {
        "enabled": enabled,
        "model_counts": counts,
        "particle_observations": particles,
    }


def diagnostics_present(diag):
    return bool(diag["enabled"] or diag["model_counts"] or diag["particle_observations"])


def print_stage_diagnostics(diag):
    if not diagnostics_present(diag):
        return
    print("\nstage diagnostics (observed calls, not frames or fps)")
    if diag["enabled"]:
        print("stage-diagnostic enabled:", int(diag["enabled"][-1]["enabled"]))
    if diag["model_counts"]:
        print("model counts:")
        for row in diag["model_counts"]:
            print(f"  stage {row['stage_id']} {row['reason_name']} {row['count']}")
    if diag["particle_observations"]:
        print("particle predicate first-seen (cap 512; contended and repeats omitted):")
        for row in diag["particle_observations"]:
            flags = ",".join(row["flag_names"]) or "none"
            caller = ("unrepresentable" if row["caller_unrepresentable"]
                      else f"0x{row['caller']:x}")
            print(f"  {row['name']} stage {row['stage_id']} flags {flags} caller {caller}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("events", type=Path)
    parser.add_argument("--names", type=Path, action="append",
                        default=[Path(__file__).resolve().parent.parent / "reference" / "effect_names.txt"])
    parser.add_argument("--kind", type=lambda v: int(v, 0), help="only this fighter/weapon kind or stage ID")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    names = load_names(p for p in args.names if p.exists())
    rows = read_events(args.events)
    latched = [r for r in rows if "latched" in r]
    requests = [r for r in rows if "hash" in r]
    for r in requests:
        r["name"] = (f"model-path 0x{r['hash']:010x}" if r["category"] == 0xfd
                     else names.get(r["hash"], f"0x{r['hash']:010x}"))
    if args.kind is not None:
        requests = [r for r in requests if r["kind"] == args.kind]
    diag = read_stage_diagnostics(args.events)
    if args.kind is not None:
        diag["model_counts"] = [row for row in diag["model_counts"] if row["stage_id"] == args.kind]
        diag["particle_observations"] = [
            row for row in diag["particle_observations"] if row["stage_id"] == args.kind]
    for row in diag["particle_observations"]:
        row["name"] = names.get(row["hash"], f"0x{row['hash']:010x}")
    if args.json:
        payload = {"latched": [row["latched"] for row in latched], "requests": requests}
        if diagnostics_present(diag):
            payload["stage_diagnostics"] = diag
        print(json.dumps(payload, indent=1))
        return
    if latched:
        print("marker latched:", latched[-1]["latched"])
    if not requests:
        print("no trace rows (codes 110/114/116) in", args.events, file=sys.stderr)
    else:
        print_trace_groups(requests)
    print_stage_diagnostics(diag)


def print_trace_groups(requests):
    by_actor = defaultdict(list)
    for r in requests:
        by_actor[(r["category"], r["kind"])].append(r)
    for (category, kind), items in sorted(by_actor.items()):
        label = {0: "fighter", 1: "weapon", 0xfe: "stage-particle", 0xfd: "stage-model"}.get(category, f"category {category}")
        print(f"\n{label} kind 0x{kind:x}: {len(items)} distinct (name, status) pairs")
        by_name = defaultdict(set)
        for r in items:
            by_name[r["name"]].add(r["status"])
        for name in sorted(by_name):
            statuses = ", ".join(f"0x{s:x}" for s in sorted(by_name[name]))
            print(f"  {name:40s} statuses {statuses}")
    unresolved = sorted({r["hash"] for r in requests if r["name"].startswith("0x")})
    if unresolved:
        print(f"\n{len(unresolved)} hashes without a name; add candidates to the names file.")


if __name__ == "__main__":
    main()
